#include <iostream> 
#include <cmath> 
using namespace std;
int main() {
    double x;     // вхідний параметр 
    double y1;    // результат для 1-го способу (скорочена форма) 
    double y2;    // результат для 2-го способу (повна форма) 
    double A;     // функціонально стала частина виразу: 5 * e^(3x) 
    double B1;    // проміжний результат для 1-го способу 
    double B2;    // проміжний результат для 2-го способу
    cout << "x = "; cin >> x;

    // Функціонально стала частина виразу
    A = 5 * exp(3 * x);

    // Спосіб 1: використання лише команд розгалуження в скороченій формі
    if (x < -1)
        B1 = sqrt(2) * pow(x, 3) - 7;
    if (x >= -1 && x < 3)
        B1 = 2 * log10(1 - x / 4);
    if (x >= 3)
        B1 = cos(x) + 3;

    y1 = A - B1;

    // Спосіб 2: використання лише команд розгалуження в повній формі
    if (x < -1)
        B2 = sqrt(2) * pow(x, 3) - 7;
    else
        if (x >= -1 && x < 3)
            B2 = 2 * log10(1 - x / 4);
        else
            B2 = cos(x) + 3;

    y2 = A - B2;

    // Вивід результатів
    cout << endl;
    cout << "1) y = " << y1 << endl;
    cout << "2) y = " << y2 << endl;

    cin.get();
    return 0;
}